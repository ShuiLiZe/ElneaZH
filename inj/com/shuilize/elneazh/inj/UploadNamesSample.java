package com.shuilize.elneazh.inj;

/**
 * Self-check fixtures for {@link UploadNames}: the expected byte strings are produced by the PC
 * side tool `tools/verify_upload_names.py` (Python zlib + base64) and pasted in here after that
 * tool has passed. The device (android zlib + our Base64) then has to reproduce them byte for
 * byte, so a drift on either side (base64 line breaks, zlib header, compression level) shows up.
 *
 * Sample shape (the real upload format): a name slot is `0x01 + len + UTF-8 bytes`.
 * Noise is mixed in on purpose: runs like ff ff ff / 7f 80 01 that would tempt a sloppy scanner.
 */
final class UploadNamesSample {
    private UploadNamesSample() {}

    /** Chinese names: translated NPC names mixed with a player-typed name. */
    static final String[] ZH = {"凯恩", "蕾娜塔", "约尔格", "铁蛋"};
    /** Fixed pinyin for the above (first letter upper case, no tones). */
    static final String[] ASCII = {"KaiEn", "LeiNaTa", "YueErGe", "TieDan"};

    /** Original sample: four name slots plus noise runs. */
    static final String RAW_HEX =
            "0000000101000000"
            + "0106e587afe681a9"
            + "ffffffff02000000"
            + "0109e895bee5a89c"
            + "e5a194000109e7ba"
            + "a6e5b094e6a0bc7f"
            + "800102030106e993"
            + "81e89b8b0101ffde"
            + "adbeef";
            // NOTE: 0x09 length for the 9-byte names; the second name's last byte is intentionally
            // part of the sample so the slot boundary is unambiguous.

    /** Expected result after replacement (regenerated by the PC tool; see tools/verify_upload_names.py). */
    static final String EXPECT_HEX =
            "0000000101000000"
            + "01054b6169456eff"
            + "ffffff0200000001"
            + "074c65694e615461"
            + "0001075975654572"
            + "47657f8001020301"
            + "0654696544616e01"
            + "01ffdeadbeef";

    /** Over-long name: replacement must be refused, bytes returned untouched. */
    static final String OVERLONG_RAW_HEX = "010201e995bf" + "0106e99381e89b8b";

    static byte[] hex(String s) {
        int n = s.length() / 2;
        byte[] b = new byte[n];
        for (int i = 0; i < n; i++) {
            b[i] = (byte) Integer.parseInt(s.substring(i * 2, i * 2 + 2), 16);
        }
        return b;
    }

    static String crc(byte[] b) {
        java.util.zip.CRC32 c = new java.util.zip.CRC32();
        c.update(b, 0, b.length);
        return Long.toHexString(c.getValue());
    }
}
